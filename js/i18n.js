const I18n = {
  lang: 'pt',
  t: function (key, vars) {
    const dict = I18N_STRINGS[this.lang] || {};
    let s = dict[key] !== undefined ? dict[key] : (I18N_STRINGS.en[key] || key);
    if (vars) {
      Object.keys(vars).forEach(function (k) {
        s = s.split('{{' + k + '}}').join(String(vars[k]));
      });
    }
    return s;
  },
  setLang: function (lang) {
    this.lang = lang === 'en' ? 'en' : 'pt';
    document.documentElement.lang = this.lang === 'en' ? 'en' : 'pt-BR';
  },
};

window.I18n = I18n;
